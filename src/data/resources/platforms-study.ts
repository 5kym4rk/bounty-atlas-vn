import type { LearningResource } from '@/schemas/entities';
import { defineResource } from '../helpers';

/**
 * Nguồn học cho API, danh tính, di động, cloud, container, mạng, desktop và nhị phân.
 *
 * Chỉ liên kết tới nguồn gốc. Không sao chép nội dung về dự án.
 */

/** Mặc định là tài liệu ở mức trung cấp; mọi trường đều ghi đè được. */
type DocInput = Omit<Parameters<typeof defineResource>[0], 'resourceType'> &
  Partial<Pick<LearningResource, 'resourceType'>>;

function doc(input: DocInput): LearningResource {
  return defineResource({ resourceType: 'documentation', difficulty: 'intermediate', ...input });
}

/** Một mục trong OWASP API Security Top 10 bản 2023. */
function apiTop10(
  id: string,
  slug: string,
  title: string,
  descriptionVi: string,
): LearningResource {
  return defineResource({
    id,
    title,
    url: `https://owasp.org/API-Security/editions/2023/en/${slug}/`,
    provider: 'OWASP',
    descriptionVi,
    resourceType: 'standard',
    domainIds: ['dom-api'],
    sourceClass: 'official-standard',
    sourceOriginNoteVi:
      'Mục cụ thể trong OWASP API Security Top 10 bản 2023, có mô tả kịch bản và khuyến nghị phòng ngừa.',
    difficulty: 'intermediate',
  });
}

/** Một RFC của IETF. */
function rfc(
  id: string,
  number: string,
  title: string,
  descriptionVi: string,
  domainIds: string[],
): LearningResource {
  return defineResource({
    id,
    title,
    url: `https://www.rfc-editor.org/rfc/rfc${number}`,
    provider: 'IETF',
    descriptionVi,
    resourceType: 'specification',
    domainIds,
    sourceClass: 'official-standard',
    sourceOriginNoteVi: 'Tiêu chuẩn IETF, bản gốc trên rfc-editor.org.',
    difficulty: 'advanced',
  });
}

